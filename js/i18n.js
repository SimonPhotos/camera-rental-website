	const originalText = new WeakMap();

	function translateTextNodes(language) {
		const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
			acceptNode(node) {
				return ['SCRIPT', 'STYLE'].includes(node.parentElement?.tagName) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
			}
		});
		const dictionary = dictionaries[language];
		let node;
		while ((node = walker.nextNode())) {
			if (!originalText.has(node)) originalText.set(node, node.nodeValue);
			const source = originalText.get(node);
			const trimmed = source.trim();
			if (!trimmed || !dictionary[trimmed]) continue;
			node.nodeValue = source.replace(trimmed, dictionary[trimmed]);
		}
	}

	function applyAttributes(language) {
		Object.entries(attributes).forEach(([selector, values]) => {
			const element = document.querySelector(selector);
			if (!element) return;
			if (values.placeholder) element.placeholder = values.placeholder[language];
			if (values.ariaLabel) element.setAttribute('aria-label', values.ariaLabel[language]);
			if (values.text) element.textContent = values.text[language];
		});
	}

	function applyLanguage(language) {
		const selectedLanguage = dictionaries[language] ? language : 'id';
		translateTextNodes(selectedLanguage);
		applyAttributes(selectedLanguage);
		document.documentElement.lang = selectedLanguage;
		document.title = selectedLanguage === 'id' ? 'Framehouse Rentals | Peralatan Profesional untuk Setiap Cerita' : 'Framehouse Rentals | Professional Equipment for Every Story';
		document.querySelectorAll('[data-language]').forEach((button) => {
			const active = button.dataset.language === selectedLanguage;
			button.classList.toggle('is-active', active);
			button.setAttribute('aria-pressed', String(active));
		});
		localStorage.setItem('framehouse-language', selectedLanguage);
		window.siteLanguage = selectedLanguage;
		document.dispatchEvent(new CustomEvent('languagechange', { detail: selectedLanguage }));
	}

	document.addEventListener('DOMContentLoaded', () => {
		const storedLanguage = localStorage.getItem('framehouse-language') || 'id';
		document.querySelectorAll('[data-language]').forEach((button) => {
			button.addEventListener('click', () => applyLanguage(button.dataset.language));
		});
		applyLanguage(storedLanguage);
	});

